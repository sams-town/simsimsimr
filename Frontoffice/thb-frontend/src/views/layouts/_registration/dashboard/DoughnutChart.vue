    plugins: {
      type: Array,
      default: () => []
    }
  },
  data() {
    return {
      chartData: {
        labels: ['Rawat Inap', 'IGD', 'Rawat Jalan'],
        datasets: [
          {
            backgroundColor: ['#F287A1', '#EC6485', '#C24CA3'],
            data: [25, 25, 50]
          }
        ]
      },
      chartOptions: {
        responsive: true,
        maintainAspectRatio: false,
        plugins: {
          legend: {
            position: 'bottom',
            align: 'center',
            labels: {
              font: {
                size: 10
              }
            },
            boxWidth: 10
          }
        }
      }
    }
  }
}
</script>
