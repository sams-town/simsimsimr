    /**
     * Soap_o_action API
     * --------------------
     * @param: canvasing_type_id
     * @param: canvasing_text
     * @param: attr1
     * @param: attr2
     * --------------------
     * @method : POST
     * @link: version/mr/soap_o_action
     **/

    public function update_put($p = 0) {
        $id         = $this->security->xss_clean($p);
        // CALL JSON POST
        $data       = $this->json_put();
        // DEFINE ATTR
        $dt_put     = $data['dt_postput'];
        $device     = $data['dt_server']['HTTP_USER_AGENT'];
        $ip         = $this->get_client_ip();
        $error      = TRUE;

        // Token Validation
        $is_valid_token = $this->authorization_token->validateToken();
        if (!empty($is_valid_token) AND $is_valid_token['status'] === TRUE) {
            # Form Validation
            $this->form_validation->set_data($dt_put);
            $this->form_validation->set_rules('canvasing_type_id', 'canvasing_type_id', 'trim|max_length[1]');
            $this->form_validation->set_rules('canvasing_text', 'canvasing_text', 'trim');
            $this->form_validation->set_rules('attr1', 'attr1', 'trim');
            $this->form_validation->set_rules('attr2', 'attr2', 'trim');
            if ($this->form_validation->run() == FALSE){
                // Form Validation Errors
                $response_data = $this->form_validation->error_array();
                $this->REST_Return(422, 'Oops, something went wrong, Please try again latter.', $response_data);
            } else {
                $model = $this->name;
                /* Start Transaction */
                $this->db->trans_start();
                $soap_o_action = $this->$model->read($id); 
                if($soap_o_action != []) {
                    $dt_soap_o_action = array(
                        'id'                    => $id,
                        'canvasing_type_id'     => isset($dt_put['canvasing_type_id']) ? $dt_put['canvasing_type_id'] : $soap_o_action[0]->canvasing_type_id,
                        'canvasing_text'        => isset($dt_put['canvasing_text']) ? $dt_put['canvasing_text'] : $soap_o_action[0]->canvasing_text,
                        'attr1'                 => isset($dt_put['attr1']) ? $dt_put['attr1'] : $soap_o_action[0]->attr1,
                        'attr2'                 => isset($dt_put['attr2']) ? $dt_put['attr2'] : $soap_o_action[0]->attr2
                    );
                    $id = $this->$model->update($id, $dt_soap_o_action);
                } else {
                    $this->REST_Return(404, 'Soap_o_action with id ' . $id . ' does not exist!');
                    return;
                }
                $this->db->trans_complete();
                /* End Transaction */
                if ($this->db->trans_status() === false) {
                    $response_data = array();
                    $this->REST_Return(422, 'Oops, something went wrong, Please try again latter.', $response_data);
                } else {
                    $response_data = $id;
                    $this->REST_Return(200, 'SUCCESS', $response_data);
                }
                return;     
            }
        } else {
            $response_data = 'Invalid Token.';
            $this->REST_Return(401, $is_valid_token['message'] ,$response_data);
            return;
        }
    }
